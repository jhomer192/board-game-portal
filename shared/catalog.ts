export type Category =
  | 'party'
  | 'social deduction'
  | 'word'
  | 'drawing'
  | 'strategy'
  | 'card game'
  | 'co-op'
  | 'classic'
  | 'family'
  | 'trivia'

export type Price = 'free' | 'freemium' | 'paid'

export interface GameLink {
  label: string
  url: string
  note?: string
}

export interface GameMeta {
  slug: string
  name: string
  tagline: string
  description: string
  minPlayers: number
  maxPlayers: number
  /** Sweet spot player counts. */
  bestPlayers: number[]
  minMinutes: number
  maxMinutes: number
  /** 1 = pick up instantly, 5 = heavy. */
  complexity: 1 | 2 | 3 | 4 | 5
  categories: Category[]
  tags: string[]
  emoji: string
  gradient: string
  links: GameLink[]
  price: Price
  /** Needs a video/voice call alongside it to work well. */
  needsCall?: boolean
}

