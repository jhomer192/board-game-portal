export const CATALOG_BY_SLUG: Record<string, GameMeta> = Object.fromEntries(CATALOG.map((g) => [g.slug, g]))

export const ALL_CATEGORIES = Object.keys(CATEGORY_INFO) as Category[]

export interface Filters {
  query: string
  category: Category | null
  players: number | null
  maxTime: number | null
  maxComplexity: number | null
  freeOnly: boolean
}

export const EMPTY_FILTERS: Filters = { query: '', category: null, players: null, maxTime: null, maxComplexity: null, freeOnly: false }

export function searchCatalog(f: Filters): GameMeta[] {
  const q = f.query.trim().toLowerCase()
  return CATALOG.filter((g) => {
    if (f.category && !g.categories.includes(f.category)) return false
    if (f.players !== null && (f.players < g.minPlayers || f.players > g.maxPlayers)) return false
    if (f.maxTime !== null && g.minMinutes > f.maxTime) return false
    if (f.maxComplexity !== null && g.complexity > f.maxComplexity) return false
    if (f.freeOnly && g.price === 'paid') return false
    if (!q) return true
    const hay = [g.name, g.tagline, g.description, ...g.categories, ...g.tags, ...g.links.map((l) => l.label)].join(' ').toLowerCase()
    return q.split(/\s+/).every((word) => hay.includes(word))
  })
}

export function formatPlayers(g: GameMeta) {
  if (g.maxPlayers >= 20) return `${g.minPlayers}+`
  return g.minPlayers === g.maxPlayers ? `${g.minPlayers}` : `${g.minPlayers}–${g.maxPlayers}`
}

export function formatTime(g: GameMeta) {
  return g.minMinutes === g.maxMinutes ? `${g.minMinutes} min` : `${g.minMinutes}–${g.maxMinutes} min`
}

